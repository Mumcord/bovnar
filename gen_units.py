#!/usr/bin/env python3
"""
gen_units.py — generate the C unit tables from src/gendata/units.bvnr.

Reads the document with the built-in bvnr_data reader (no libbvnr) and emits:

    include/bovnar_units.gen.h               enum body: bu_<name> = <id>,
    <gendir>/bovnar_si_conv_table.gen.inc    si_conv_table rows
    <gendir>/bovnar_base_unit_str.gen.inc    base_unit_str() switch cases
    <gendir>/bovnar_bu_table.gen.inc         bu_table rows (aliases, byte lengths)
    <gendir>/bovnar_bu_index.gen.inc         bu_first_for_len / bu_max_len
    <gendir>/bovnar_prefix_policy.gen.inc    per-unit prefix-policy entries
    <gendir>/bovnar_compact_except.gen.inc   compact spellings refused as units

The public *.gen.h enum header goes to include/ (committed). The *.gen.inc
snippets are build artifacts: <gendir> is $BVNR_GENERATED_DIR (set by CMake,
default build/generated). A host-side step — needs only Python 3.

Usage:
    [BVNR_GENERATED_DIR=dir] python3 gen_units.py [path/to/units.bvnr]
"""
import re
import sys
import os

REPO = os.path.dirname(os.path.abspath(__file__))   # this script lives at repo root
GENDATA = os.path.join(REPO, "src", "gendata")       # the *.bvnr source of truth
# Generated .inc snippets go here (a build dir, not committed); overridable so
# CMake can point at $<BINARY_DIR>/generated. The public *.gen.h enum headers
# stay in include/.
GENDIR = os.environ.get("BVNR_GENERATED_DIR",
                        os.path.join(REPO, "build", "generated"))
import bvnr_data  # noqa: E402  -- standalone reader; no libbvnr dependency

# SI base dimensions, in the canonical order of the dims[] vector the C tables
# use. The data document names them (e.g. .dims = {.length = 1; .time = -2;})
# and omits the zeros; the generator expands to the full ordered vector.
DIM_NAMES = ["length", "mass", "time", "current",
             "temperature", "amount", "luminosity"]
DIM_INDEX = {name: i for i, name in enumerate(DIM_NAMES)}


def dims_to_vector(dims, unitname):
    """Accept a named struct {.length=1; .time=-2;} (zeros omitted) or a bare
    7-element list, and return the ordered [len, mass, time, ...] vector."""
    vec = [0] * len(DIM_NAMES)
    if isinstance(dims, list):
        if len(dims) != len(DIM_NAMES):
            raise SystemExit("%s: dims list must have %d entries"
                             % (unitname, len(DIM_NAMES)))
        return list(dims)
    for name, val in dims.items():
        if name not in DIM_INDEX:
            raise SystemExit("%s: unknown dimension %r (expected one of %s)"
                             % (unitname, name, ", ".join(DIM_NAMES)))
        vec[DIM_INDEX[name]] = val
    return vec


# prefix policy symbol -> generated C enumerator
POLICY = {
    "default": "BVN_PFX_DEFAULT",
    "info":    "BVN_PFX_INFO",
    "german":  "BVN_PFX_GERMAN",
    "ratio":   "BVN_PFX_RATIO",
    "none":    "BVN_PFX_NONE",
}

BANNER = ("/* GENERATED by gen_units.py from src/gendata/units.bvnr — "
          "DO NOT EDIT.\n"
          " * SPDX-License-Identifier: MIT */\n")


def c_string_literal(s):
    """Encode a Python str as one or more adjacent C string literals.

    Every non-printable / non-ASCII byte becomes a \\xNN escape; a run of
    escapes is closed before the next plain byte so that a following hex digit
    (or a letter like the "C" in "°C") is never absorbed into the escape.
    Matches the hand-written style in bovnar_utils.c, e.g.  "\\xc2\\xb0" "C".
    """
    chunks = []          # list of (is_escape, text)
    buf = ""
    buf_esc = None
    for b in s.encode("utf-8"):
        printable = 0x20 <= b < 0x7f and b not in (0x22, 0x5c)  # not " or \
        esc = not printable
        if buf and buf_esc != esc:
            chunks.append((buf_esc, buf))
            buf = ""
        buf += ("\\x%02x" % b) if esc else chr(b)
        buf_esc = esc
    if buf:
        chunks.append((buf_esc, buf))
    if not chunks:
        return '""'
    return " ".join('"%s"' % text for _, text in chunks)


def c_double_literal(x):
    """Shortest decimal that round-trips to the same IEEE-754 double."""
    r = repr(float(x))
    # repr() already yields '.0'/'e' forms; guarantee it reads as a double.
    if "." not in r and "e" not in r and "E" not in r and "inf" not in r:
        r += ".0"
    return r


def byte_len(s):
    return len(s.encode("utf-8"))


# The native units are the "10" block of the base-unit id space: ids
# NATIVE_FIRST .. NATIVE_FIRST+BLOCK_SIZE-1, and this generator requires them to
# be CONTIGUOUS from the first. Contiguity is what lets the dense table slot be
# plain subtraction (BVN_SLOT_NATIVE below) instead of a lookup, and what lets
# the C side answer "is this id a native unit" in two comparisons. See the
# id-space layout note in include/bovnar.h.
NATIVE_FIRST = 100000
BLOCK_SIZE = 10000
# Slot 0 of every dense table is bu_none, so the native rows start at 1.
SLOT_NATIVE_BASE = 1


def load_units(path):
    with open(path, "rb") as f:
        doc = bvnr_data.load(f.read())
    units = doc["units"]
    # Validate the stable-id contract up front. This used to allow any unique
    # positive id, which is what let the space grow the holes it had; the block
    # layout replaces that with an exact shape, so a mis-typed id is a build
    # failure at the file that owns it rather than a silent hole in a table
    # somewhere downstream.
    ids = [u["id"] for u in units]
    seen = {}
    for u in units:
        i = u["id"]
        if i in seen:
            raise SystemExit("duplicate id %d (%s and %s)"
                             % (i, seen[i], u["name"]))
        seen[i] = u["name"]
    want = list(range(NATIVE_FIRST, NATIVE_FIRST + len(units)))
    if ids != want:
        bad = next((n for n, (a, b) in enumerate(zip(ids, want)) if a != b),
                   len(want))
        raise SystemExit(
            "unit ids must be contiguous and ascending from %d: record %d (%s) "
            "has id %d, expected %d"
            % (NATIVE_FIRST, bad, units[bad]["name"], ids[bad], want[bad]))
    if len(units) > BLOCK_SIZE:
        raise SystemExit("the native unit block holds %d ids; this file has %d"
                         % (BLOCK_SIZE, len(units)))
    return units


def gen_enum(units):
    out = [BANNER]
    for u in units:
        out.append("\tbu_%-12s = %6d,\n" % (u["name"], u["id"]))
    out.append("""
/* The native block's bounds, and the dense table slot of a unit in it.
 *
 * Every table the library indexes by base unit is DENSE — one row per defined
 * unit, not one row per id — because the id space is deliberately sparse (each
 * vocabulary gets its own 10000-wide block, so growing one shifts no other).
 * BVN_SLOT_NATIVE turns an id back into that row index, and is written as
 * arithmetic on the enumerator so it can be a designated-initialiser index in
 * the generated table rows: the row and the enum cannot drift apart. */
""")
    out.append("#define BVN_UNIT_NATIVE_FIRST     %d\n" % NATIVE_FIRST)
    out.append("#define BVN_UNIT_NATIVE_LAST      %d\n"
               % (NATIVE_FIRST + len(units) - 1))
    out.append("#define BVN_UNIT_NATIVE_COUNT     %d\n" % len(units))
    out.append("#define BVN_UNIT_SLOT_NATIVE_BASE %d\n" % SLOT_NATIVE_BASE)
    out.append("#define BVN_SLOT_NATIVE(b) \\\n"
               "\t(BVN_UNIT_SLOT_NATIVE_BASE + ((int)(b) - BVN_UNIT_NATIVE_FIRST))\n")
    return "".join(out)


# A decimal carrying this many significant digits is the repr of a double, not a
# deliberately written exact value — i.e. it is a ROUNDED approximation of the
# unit's true factor. Recovering a "exact" rational from it would bake that
# rounding error into a conversion the library advertises as lossless, so such a
# unit must state the truth explicitly (see check_exactness below).
ROUNDED_DECIMAL_SIGDIGITS = 16


def _sig_digits(lit):
    from decimal import Decimal
    return len(Decimal(lit).normalize().as_tuple().digits)


def check_exactness(units):
    """Refuse to generate a conversion table that silently claims a rounded
    double is an exact rational.

    The table's whole purpose is lossless conversion, so every factor/offset must
    be one of three things, stated in the source rather than inferred:

      * a short exact decimal        — `.factor = 0.0254;` (inch, exact by
                                       definition), recovered exactly below;
      * a non-terminating rational   — `.factor_num`/`.factor_den` (e.g. °F's
                                       slope 5/9), which no decimal can express;
      * genuinely irrational         — `.exact = false` (π-based units), rejected
                                       at conversion time.

    A 16+ digit decimal with none of those markers means somebody pasted a double
    repr and the true value was lost. That is exactly how °R (5/9) once shipped a
    wrong "exact" answer while °F, hand-overridden, correctly refused."""
    bad = []
    for u in units:
        if not bool(u.get("exact", True)):
            continue                      # irrational: never claimed exact
        for key in ("factor", "offset"):
            if u.get(key + "_num") is not None and u.get(key + "_den") is not None:
                continue                  # truth stated explicitly
            lit = c_double_literal(u[key])
            if _sig_digits(lit) >= ROUNDED_DECIMAL_SIGDIGITS:
                bad.append("  %-16s .%s = %s  (%d significant digits)"
                           % (u["name"], key, lit, _sig_digits(lit)))
    if bad:
        raise SystemExit(
            "gen_units: these units declare a %d+ digit decimal — the repr of a "
            "double, i.e. a rounded value — but claim an exact rational:\n%s\n\n"
            "Give each one either .%s_num/.%s_den with the true rational, or "
            ".exact = false if the true value is irrational."
            % (ROUNDED_DECIMAL_SIGDIGITS, "\n".join(bad), "<factor|offset>",
               "<factor|offset>"))


def exact_rational(u, key):
    """Return the exact (numerator, denominator) rational for a unit's `factor`
    or `offset`, reduced to lowest terms.

    An explicit .<key>_num / .<key>_den override in the source wins — use it for
    a factor whose true value is a NON-terminating rational (e.g. fahrenheit's
    slope 5/9, offset 45967/180), which the stored decimal only approximates.
    Otherwise the rational is recovered exactly from the declared decimal
    (Decimal keeps every written digit, incl. exponent form), so a conversion
    introduces no error beyond the library's own declared factor. Units whose
    factor is genuinely irrational (π-based angles) carry .exact = false and are
    reported inexact at conversion time regardless of what this returns.

    check_exactness has already rejected the dangerous middle case — a rounded
    double repr presented as an exact decimal — so the fallback below is only
    ever reached for a value the source really does state exactly."""
    from fractions import Fraction
    from decimal import Decimal
    n = u.get(key + "_num")
    d = u.get(key + "_den")
    if n is not None and d is not None:
        return Fraction(int(n), int(d))
    return Fraction(Decimal(c_double_literal(u[key])))


def pi_form(u):
    """The three trailing columns of a conversion row: the factor of a π-defined
    unit as (pi_num / pi_den) · π^pi_power, or NULL, NULL, 0.

    A unit whose factor is irrational carries .exact = false, and that is all a
    conversion to SI needs to know. A conversion between TWO such units needs
    more: 1 rev is 360° exactly, because the π on each side cancels, and only the
    rational parts can show that. So a π-based unit states them, and
    bvn_unit_convert_rational is exact wherever the powers agree.

    Checked against .factor here, because the two are written by hand side by
    side and a row whose rational part disagreed with its own double would make
    the exact path and the approximate one answer differently."""
    import math
    from fractions import Fraction
    has = [k in u for k in ("pi_num", "pi_den", "pi_power")]
    if not any(has):
        return "NULL, NULL, 0"
    if not all(has):
        raise SystemExit("unit %r: .pi_num, .pi_den and .pi_power go together"
                         % u["name"])
    if bool(u.get("exact", True)) or u["affine"]:
        raise SystemExit("unit %r: a π form belongs to a non-affine unit with "
                         ".exact = false" % u["name"])
    fr = Fraction(int(u["pi_num"]), int(u["pi_den"]))
    power = int(u["pi_power"])
    if fr <= 0 or power == 0:
        raise SystemExit("unit %r: a π form needs a positive rational and a "
                         "non-zero power" % u["name"])
    want = float(c_double_literal(u["factor"]))
    got = float(fr) * math.pi ** power
    if abs(got - want) > 4e-16 * abs(want):
        raise SystemExit("unit %r: (%s)·π^%d = %r but .factor says %r"
                         % (u["name"], fr, power, got, want))
    return '"%d", "%d", %d' % (fr.numerator, fr.denominator, power)


def gen_conv_table(units):
    check_exactness(units)
    out = [BANNER]
    for u in units:
        nm = "bu_" + u["name"]
        dims = ", ".join("%2d" % d for d in dims_to_vector(u["dims"], u["name"]))
        fr = exact_rational(u, "factor")
        of = exact_rational(u, "offset")
        exact = bool(u.get("exact", True))
        out.append(
            "\t[BVN_SLOT_NATIVE(%-14s] = { %-14s %-22s {%s}, %-6s %-14s "
            "\"%d\", \"%d\", \"%d\", \"%d\", %s, %s },\n" % (
                nm + ")", nm + ",",
                c_double_literal(u["factor"]) + ",",
                dims,
                ("true," if u["affine"] else "false,"),
                c_double_literal(u["offset"]) + ",",
                fr.numerator, fr.denominator, of.numerator, of.denominator,
                ("true" if exact else "false"),
                pi_form(u),
            ))
    return "".join(out)


def gen_base_unit_str(units):
    out = [BANNER]
    for u in units:
        out.append("\tcase bu_%-12s return %s;\n"
                   % (u["name"] + ":", c_string_literal(u["symbol"])))
    return "".join(out)


BU_LEN_INDEX_SIZE = 32  # must match BU_LEN_INDEX_SIZE in bovnar_utils.c


def parse_rows(units):
    """The (spelling, base, id) parse rows, ordered by DESCENDING byte length
    (the suffix matcher requires longest-first; see bovnar_utils.c). Each
    spelling is exactly an alias from the data file — the canonical symbol is
    NOT auto-added, so the table reproduces the hand-written bu_table verbatim.
    """
    rows = []
    for u in units:
        base = "bu_" + u["name"]
        for sp in u["aliases"]:
            rows.append((sp, base, u["id"]))
    rows.sort(key=lambda r: (-byte_len(r[0]), r[2], r[0]))
    return rows


def gen_parse_table(rows):
    out = [BANNER]
    for sp, base, _ in rows:
        lit = c_string_literal(sp)
        out.append("\t{ %-22s %2d, %s },\n" % (lit + ",", byte_len(sp), base))
    return "".join(out)


def gen_bu_index(rows):
    """bu_first_for_len[L] = number of spellings strictly longer than L bytes
    (rows are length-sorted, so that is the index of the first entry of length
    <= L); bu_max_len = the longest spelling. Recomputed by the C self-check
    test, which asserts it equals these literals — so they must stay in sync."""
    lens = [byte_len(sp) for sp, _, _ in rows]
    max_len = max(lens) if lens else 0
    if max_len >= BU_LEN_INDEX_SIZE:
        raise SystemExit("bu_max_len %d >= BU_LEN_INDEX_SIZE %d — widen the "
                         "index in bovnar_utils.c" % (max_len, BU_LEN_INDEX_SIZE))
    first = [sum(1 for x in lens if x > L) for L in range(BU_LEN_INDEX_SIZE)]
    out = [BANNER]
    out.append("static const uint16_t bu_first_for_len[BU_LEN_INDEX_SIZE] = {\n")
    for i in range(0, BU_LEN_INDEX_SIZE, 8):
        out.append("\t" + " ".join("%4d," % v for v in first[i:i + 8]) + "\n")
    out.append("};\n")
    out.append("static const uint32_t bu_max_len = %du;\n" % max_len)
    return "".join(out)


def check_unit_string_bound(units, prefixes):
    """Refuse to generate a table whose longest unit outgrows BVNR_UNIT_STRING_MAX.

    bvn_unit_to_string returns -1 when the text does not fit AND writes no NUL, so
    a caller that ignores the return and formats the buffer with "%s" reads past
    it. That was a real stack-buffer-overflow in `bovnar events -d`. Every unit
    buffer in the tree is now sized from that macro, which makes the macro a
    promise about THIS DATA -- so adding a longer prefixable symbol has to fail
    the build rather than quietly shrink the margin to nothing.

    The bound mirrors the formatter: per component a prefix, a '~', the canonical
    symbol and an exponent; the six-byte "⁻⁹" counts because an all-negative unit
    is written as a flat product rather than split over a '/', which is the one
    shape that renders negative exponents at full width.
    """
    hdr = os.path.join(REPO, "include", "bovnar.h")
    with open(hdr, encoding="utf-8") as f:
        text = f.read()
    m = re.search(r"#define\s+BVNR_UNIT_STRING_MAX\s+(\d+)", text)
    if not m:
        raise SystemExit("gen_units: BVNR_UNIT_STRING_MAX is not defined in "
                         "include/bovnar.h -- nothing to check the bound against")
    declared = int(m.group(1))
    # Read the component count from the header rather than keeping a second
    # copy here. It used to be a module constant with a "must match bovnar.h"
    # comment, which is the kind of duplication that is correct until the day
    # one of the two moves.
    mc = re.search(r"#define\s+BVNR_MAX_UNIT_COMPONENTS\s+(\d+)", text)
    if not mc:
        raise SystemExit("gen_units: BVNR_MAX_UNIT_COMPONENTS is not defined "
                         "in include/bovnar.h")
    ncomp = int(mc.group(1))
    pfx_max = max(byte_len(p["symbol"])
                  for sysname in ("si_prefixes", "iec_prefixes")
                  for p in prefixes[sysname])
    NO_PREFIX = ("german", "ratio", "none")
    sym_max = max(byte_len(u["symbol"]) + (pfx_max + 1 if u["prefix"] not in NO_PREFIX
                                           else 0)
                  for u in units)
    # "⁻¹⁰⁰" as bvn_write_exponent_suffix emits it: ⁻ and ⁰ are three bytes
    # each, ¹ is two, so the widest exponent is 3+2+3+3 = 11. One spare byte
    # keeps the arithmetic honest if a digit's encoding width ever changes.
    EXP_MAX = 12
    SEP     = 2                      # "·"
    worst = (ncomp * (sym_max + EXP_MAX) + (ncomp - 1) * SEP + 1)
    if worst > declared:
        raise SystemExit(
            "gen_units: the longest unit this table can emit needs %d bytes, but "
            "BVNR_UNIT_STRING_MAX in include/bovnar.h is %d. Raise it (and check "
            "every buffer sized from it), or shorten the symbol that grew."
            % (worst, declared))
    return worst, declared




# Spellings that are BOTH a whole alias and a prefix + another alias, and were
# so before this check existed. Every one is settled by the longest-alias rule
# and settled the way units.bvnr's header says: "a bare alias always wins over a
# prefixed reading ("min" is the minute, never milli-inch) and no existing
# document can change meaning".
#
# They are listed rather than derived because the rule that matters is
# HISTORICAL: an old collision is a decision already taken and already shipped,
# a new one is a spelling somebody is about to redefine. The list is what tells
# those apart, and it is short and closed — adding a unit does not add to it.
KNOWN_ALIAS_SHADOWS = {
    # symbol      the prefixed reading it also has
    "PS":   "P + S     (petasiemens)",
    "at":   "a + t     (attotonne)",
    "au":   "a + u     (attodalton)",
    "cd":   "c + d     (centiday)",
    "ch":   "c + h     (centihour)",
    "ct":   "c + t     (centitonne)",
    "dB":   "d + B     (decibyte)",
    "ft":   "f + t     (femtotonne)",
    "kat":  "k + at    (kilo technical atmosphere)",
    "kph":  "k + ph    (kilophot)",
    "min":  "m + in    (milli-inch)",
    "mph":  "m + ph    (milliphot)",
    "nmi":  "n + mi    (nanomile)",
    "pH":   "p + H     (picohenry)",
    "ph":   "p + h     (picohour)",
    "pt":   "p + t     (picotonne)",
    "qt":   "q + t     (quectotonne)",
    "rd":   "r + d     (ronnaday)",
    "yd":   "y + d     (yoctoday)",
}


def check_alias_prefix_collisions(units, prefixes):
    """Refuse an alias that changes what an EXISTING spelling means.

    A prefix and an alias are written with nothing between them in the compact
    form, so `<prefix><alias>` is a spelling the parser already resolves. Adding
    a new alias that IS such a concatenation silently re-points it: the longest
    matching alias wins, so the new whole-token alias beats the prefixed
    reading, and a document that meant one unit now means another.

    This is not hypothetical. `RT` was proposed as the symbol for the ton of
    refrigeration; `R` is the ronna prefix and `T` the tesla, so `RT` had been
    the ronnatesla since prefixes and units first met. `TR` is no better — `T`
    is tera and `R` the roentgen. Both would have changed an existing spelling,
    which the header of units.bvnr forbids in as many words: "no existing
    document can change meaning".

    A collision is a build failure at the file that owns it, with both readings
    named, rather than a difference somebody notices in a diff of parse results
    — which is how this one was noticed.

    KNOWN_ALIAS_SHADOWS above is the set that predates the check. Those are not
    exceptions to the rule; they are the rule's other half. The longest-alias
    match resolves each of them to the whole token deliberately and always has,
    which is why `min` is the minute and `cd` the candela. What must not happen
    is a NEW alias joining that set, because then a spelling changes hands.

    The compact-form exceptions are NOT an escape hatch: they make a spelling an
    ERROR, which is the right answer for a token only the author can resolve,
    and no answer at all for one this table has quietly redefined.
    """
    pfx = []
    for system in ("si_prefixes", "iec_prefixes"):
        for p in prefixes[system]:
            for a in p["aliases"]:
                pfx.append(a)
    alias_of = {}
    for u in units:
        for a in u["aliases"]:
            alias_of.setdefault(a, u["name"])
    bad = []
    for a, owner in sorted(alias_of.items()):
        for p in pfx:
            if not a.startswith(p) or len(a) == len(p):
                continue
            tail = a[len(p):]
            other = alias_of.get(tail)
            if other is not None and other != owner:
                if a in KNOWN_ALIAS_SHADOWS:
                    continue          # settled long ago; see the note above
                bad.append("  %-14s is bu_%s, and also reads as %s + %s = bu_%s"
                           % (a, owner, p, tail, other))
    if bad:
        raise SystemExit(
            "gen_units: these spellings mean two different units — the whole "
            "token names one and the compact prefix form names another, and the "
            "longest-alias rule silently picks the first:\n%s\n\n"
            "Choose a symbol that is not a prefix followed by another unit's "
            "spelling. See check_alias_prefix_collisions in gen_units.py."
            % "\n".join(bad))
    return len(alias_of)


def gen_prefix_policy(units):
    out = [BANNER]
    for u in units:
        pol = u["prefix"]
        if pol not in POLICY:
            raise SystemExit("unknown prefix policy %r for %s"
                             % (pol, u["name"]))
        out.append("\t[BVN_SLOT_NATIVE(bu_%-14s = %s,\n"
                   % (u["name"] + ")]", POLICY[pol]))
    return "".join(out)


def compact_decompose(spelling, units, prefixes):
    """Split a compact spelling the way bvn_parse_single_unit_component does:
    longest matching alias suffix, and whatever precedes it must be a prefix.
    Returns (prefix_name, unit_name) or None if the spelling would not parse as
    a compact prefixed unit in the first place."""
    aliases = {}
    for u in units:
        for a in u["aliases"]:
            aliases.setdefault(byte_len(a), {})[a] = u["name"]
    if spelling in aliases.get(byte_len(spelling), {}):
        return None                      # a bare alias: the compact form never runs
    pfx = {}
    for system in ("si_prefixes", "iec_prefixes"):
        for p in prefixes[system]:
            for a in p["aliases"]:
                pfx[a] = p["name"]
    for blen in sorted(aliases, reverse=True):
        for alias, uname in aliases[blen].items():
            if not spelling.endswith(alias) or spelling == alias:
                continue
            head = spelling[:-len(alias)]
            return (pfx[head], uname) if head in pfx else None
    return None


def load_compact_exceptions(doc, units, path):
    """The compact spellings that must stay a parse error (see units.bvnr).

    Each one is checked against the parse rules the C side will apply: an entry
    that would never have been accepted anyway is dead weight — most likely a
    typo — and a silently ignored denial is worse than a build failure."""
    excs = doc.get("compact_exceptions", [])
    prefixes = bvnr_data.load(
        open(os.path.join(os.path.dirname(os.path.abspath(path)),
                          "prefixes.bvnr"), "rb").read())
    out, seen = [], set()
    for e in excs:
        sp = e["spelling"]
        if sp in seen:
            raise SystemExit("duplicate compact exception %r" % sp)
        seen.add(sp)
        if compact_decompose(sp, units, prefixes) is None:
            raise SystemExit(
                "compact exception %r does not parse as a compact prefixed "
                "unit, so refusing it changes nothing — fix or drop it" % sp)
        out.append((sp, e["why"]))
    return out


def gen_compact_except(excs):
    out = [BANNER]
    for sp, why in excs:
        out.append("\t{ %-8s %2d },  /* %s */\n"
                   % (c_string_literal(sp) + ",", byte_len(sp), why))
    return "".join(out)


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(GENDATA, "units.bvnr")
    units = load_units(path)
    with open(path, "rb") as f:
        excs = load_compact_exceptions(bvnr_data.load(f.read()), units, path)

    prefixes = bvnr_data.load(
        open(os.path.join(GENDATA, "prefixes.bvnr"), "rb").read())
    worst_unit_str, unit_str_cap = check_unit_string_bound(units, prefixes)
    check_alias_prefix_collisions(units, prefixes)

    rows = parse_rows(units)
    # WIRED fragments are written into the source tree where they are #include'd
    # (and where amalgamate.py resolves them by basename). The prefix policy stays
    # a preview in out/ — bvn_prefix_unit_valid keeps its range checks for now.
    inc = os.path.join(REPO, "include")
    utl = GENDIR
    os.makedirs(utl, exist_ok=True)
    artifacts = {
        os.path.join(inc, "bovnar_units.gen.h"):           gen_enum(units),
        os.path.join(utl, "bovnar_si_conv_table.gen.inc"): gen_conv_table(units),
        os.path.join(utl, "bovnar_base_unit_str.gen.inc"): gen_base_unit_str(units),
        os.path.join(utl, "bovnar_bu_table.gen.inc"):      gen_parse_table(rows),
        os.path.join(utl, "bovnar_bu_index.gen.inc"):      gen_bu_index(rows),
        os.path.join(utl, "bovnar_prefix_policy.gen.inc"): gen_prefix_policy(units),
        os.path.join(utl, "bovnar_compact_except.gen.inc"): gen_compact_except(excs),
    }
    for dest, text in artifacts.items():
        bvnr_data.write_if_changed(dest, text)

    print("generated %d units (%d parse rows, %d compact exceptions; "
          "longest emitted unit %d bytes, cap %d)"
          % (len(units), len(rows), len(excs), worst_unit_str,
             unit_str_cap))
    print("  wired: bovnar_units.gen.h, bovnar_si_conv_table.gen.inc,")
    print("         bovnar_base_unit_str.gen.inc, bovnar_bu_table.gen.inc,")
    print("         bovnar_bu_index.gen.inc, bovnar_prefix_policy.gen.inc,")
    print("         bovnar_compact_except.gen.inc")


if __name__ == "__main__":
    main()
