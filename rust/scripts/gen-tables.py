#!/usr/bin/env python3
"""Generate the unit tables in src/units/gen/ from the upstream data.

Usage: python3 -I scripts/gen-tables.py <upstream-source-dir> [--check]

Reads src/gendata/units.bvnr, prefixes.bvnr and currencies.bvnr of the
upstream C reference and writes static, sorted Rust slices: the parser looks
spellings up by binary search, so nothing is built at run time.

It also writes one table file per shipped unit profile (doc/11) from
unece.bvnr, qudt.bvnr, qudt-qk.bvnr, udunits.bvnr and om.bvnr. The UCUM and
CF data files are never opened: those profiles are not shipped.

The upstream generators' own loaders and validators are imported from the
upstream tree, so a data file the C build would refuse is refused here too,
and the exact rationals are recovered by the very code that produces the C
tables.

The output is a pure function of the data files and the upstream commit, so
CI can regenerate with --check and fail on any difference.
"""

import os
import subprocess
import sys

OUT_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                       os.pardir, "src", "units", "gen")


def rust_str(s):
    """A Rust string literal; non-ASCII stays literal UTF-8 for readability."""
    out = ['"']
    for ch in s:
        if ch in '"\\':
            out.append("\\" + ch)
        elif ord(ch) < 0x20 or ord(ch) == 0x7F:
            out.append("\\u{%x}" % ord(ch))
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def rust_f64(x, c_double_literal):
    lit = c_double_literal(x)
    if lit in ("inf", "-inf", "nan"):
        raise SystemExit("non-finite factor %r" % x)
    return lit


def upstream_commit(upstream):
    try:
        return subprocess.run(
            ["git", "-C", upstream, "rev-parse", "HEAD"],
            check=True, capture_output=True, text=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError) as e:
        raise SystemExit("cannot read the upstream commit: %s" % e)


def header(commit, what):
    return ("// @generated by scripts/gen-tables.py from upstream %s\n"
            "// (src/gendata/%s). Do not edit; regenerate instead.\n\n"
            % (commit, what))


def utf8(s):
    return s.encode("utf-8")


def gen_units(gu, bvnr_data, upstream, commit):
    path = os.path.join(upstream, "src", "gendata", "units.bvnr")
    units = gu.load_units(path)
    with open(path, "rb") as f:
        excs = gu.load_compact_exceptions(bvnr_data.load(f.read()), units, path)
    gu.check_exactness(units)

    out = [header(commit, "units.bvnr")]
    out.append("use super::super::data::{PrefixPolicy, UnitRow};\n\n")
    out.append("/// Id of the first native base unit; row `i` of [`UNITS`] has id "
               "`NATIVE_FIRST + i`.\n")
    out.append("pub(crate) const NATIVE_FIRST: u32 = %d;\n\n" % gu.NATIVE_FIRST)

    for u in units:
        out.append("pub(crate) const BU_%s: u32 = %d;\n"
                   % (u["name"].upper(), u["id"]))
    out.append("\n")

    policy = {"default": "Default", "info": "Info", "german": "German",
              "ratio": "Ratio", "none": "None"}
    out.append("/// One row per native base unit, in id order.\n")
    out.append("pub(crate) static UNITS: [UnitRow; %d] = [\n" % len(units))
    for u in units:
        if u["prefix"] not in policy:
            raise SystemExit("unknown prefix policy %r for %s"
                             % (u["prefix"], u["name"]))
        dims = gu.dims_to_vector(u["dims"], u["name"])
        if any(not -128 <= d <= 127 for d in dims):
            raise SystemExit("dimension exponent out of i8 range in %s" % u["name"])
        fr = gu.exact_rational(u, "factor")
        of = gu.exact_rational(u, "offset")
        pi = gu.pi_form(u)
        if pi == "NULL, NULL, 0":
            pi_rs = "None"
        else:
            num, den, power = [p.strip().strip('"') for p in pi.split(",")]
            pi_rs = 'Some(("%s", "%s", %d))' % (num, den, int(power))
        out.append(
            "    UnitRow {\n"
            "        name: %s,\n"
            "        symbol: %s,\n"
            "        factor: %s,\n"
            "        dims: [%s],\n"
            "        affine: %s,\n"
            "        offset: %s,\n"
            "        policy: PrefixPolicy::%s,\n"
            "        factor_num: \"%d\",\n"
            "        factor_den: \"%d\",\n"
            "        offset_num: \"%d\",\n"
            "        offset_den: \"%d\",\n"
            "        exact: %s,\n"
            "        pi: %s,\n"
            "    },\n"
            % (rust_str(u["name"]), rust_str(u["symbol"]),
               rust_f64(u["factor"], gu.c_double_literal),
               ", ".join(str(d) for d in dims),
               "true" if u["affine"] else "false",
               rust_f64(u["offset"], gu.c_double_literal),
               policy[u["prefix"]],
               fr.numerator, fr.denominator, of.numerator, of.denominator,
               "true" if bool(u.get("exact", True)) else "false", pi_rs))
    out.append("];\n\n")

    # Every accepted spelling, sorted by bytes for binary search. Where two
    # units claim one spelling the C table, ordered by (length, id), lets the
    # lower id win; keep that one.
    owner = {}
    for u in units:
        for a in u["aliases"]:
            owner.setdefault(a, u["id"])
    aliases = sorted(owner.items(), key=lambda kv: utf8(kv[0]))
    max_len = max(len(utf8(a)) for a, _ in aliases)
    out.append("/// Length in bytes of the longest spelling in [`ALIASES`].\n")
    out.append("pub(crate) const ALIAS_MAX_LEN: usize = %d;\n\n" % max_len)
    out.append("/// Every accepted spelling and the id of its unit, sorted by bytes.\n")
    out.append("pub(crate) static ALIASES: [(&str, u32); %d] = [\n" % len(aliases))
    for a, i in aliases:
        out.append("    (%s, %d),\n" % (rust_str(a), i))
    out.append("];\n\n")

    out.append("/// Compact prefixed spellings that stay a parse error, sorted by "
               "bytes.\n")
    out.append("pub(crate) static COMPACT_EXCEPTIONS: [&str; %d] = [\n" % len(excs))
    for sp, why in sorted(excs, key=lambda e: utf8(e[0])):
        out.append("    // %s\n    %s,\n" % (why, rust_str(sp)))
    out.append("];\n")
    return "".join(out), len(units), len(aliases)


def gen_prefixes(gp, bvnr_data, upstream, commit):
    path = os.path.join(upstream, "src", "gendata", "prefixes.bvnr")
    with open(path, "rb") as f:
        doc = bvnr_data.load(f.read())
    si, iec = doc["si_prefixes"], doc["iec_prefixes"]
    gp.check(si, "si")
    gp.check(iec, "iec")

    out = [header(commit, "prefixes.bvnr")]
    out.append("use super::super::data::{PrefixRow, PrefixSystem};\n\n")
    for table, rows, base in (("SI_PREFIXES", si, 10), ("IEC_PREFIXES", iec, 2)):
        out.append("/// Row `i` is the prefix with id `i + 1` (id 0 is \"no prefix\"); "
                   "the factor is %d^exp.\n" % base)
        out.append("pub(crate) static %s: [PrefixRow; %d] = [\n" % (table, len(rows)))
        for p in rows:
            out.append("    PrefixRow { name: %s, symbol: %s, exp: %d },\n"
                       % (rust_str(p["name"]), rust_str(p["symbol"]), p["exp"]))
        out.append("];\n\n")

    # The C parser tries the IEC table before the SI one, so an IEC spelling
    # would win a clash; there is none today, and a future one must be looked
    # at rather than resolved silently.
    entries = {}
    for system, rows in (("Iec", iec), ("Si", si)):
        for p in rows:
            for a in p["aliases"]:
                if a in entries:
                    raise SystemExit("prefix spelling %r is both SI and IEC" % a)
                entries[a] = (system, p["id"])
    out.append("/// Every accepted prefix spelling, sorted by bytes.\n")
    out.append("pub(crate) static PREFIX_ALIASES: [(&str, PrefixSystem, u8); %d] = [\n"
               % len(entries))
    for a, (system, pid) in sorted(entries.items(), key=lambda kv: utf8(kv[0])):
        out.append("    (%s, PrefixSystem::%s, %d),\n" % (rust_str(a), system, pid))
    out.append("];\n")
    return "".join(out), len(si) + len(iec)


def gen_currencies(gc, bvnr_data, upstream, commit):
    path = os.path.join(upstream, "src", "gendata", "currencies.bvnr")
    with open(path, "rb") as f:
        curr = bvnr_data.load(f.read())["currencies"]
    gc.validate(curr)

    out = [header(commit, "currencies.bvnr")]
    out.append("/// Id of the first currency; row `i` of [`CURRENCIES`] has id "
               "`CURRENCY_FIRST + i`.\n")
    out.append("pub(crate) const CURRENCY_FIRST: u32 = %d;\n\n" % gc.CURRENCY_FIRST)
    out.append("/// ISO 4217 (or crypto asset) codes in id order.\n")
    out.append("pub(crate) static CURRENCIES: [&str; %d] = [\n" % len(curr))
    for c in curr:
        out.append("    %s,\n" % rust_str(c["code"]))
    out.append("];\n\n")
    out.append("/// The codes sorted by bytes, each with its row in [`CURRENCIES`].\n")
    out.append("pub(crate) static CURRENCY_INDEX: [(&str, u16); %d] = [\n" % len(curr))
    for idx, c in sorted(enumerate(curr), key=lambda ic: utf8(ic[1]["code"])):
        out.append("    (%s, %d),\n" % (rust_str(c["code"]), idx))
    out.append("];\n")
    return "".join(out), len(curr)


# The profiles this crate ships, each behind the cargo feature of that name.
# UCUM and CF are deliberately absent; their data files are never read.
SHIPPED_PROFILES = ("unece", "qudt", "qudt-qk", "udunits", "om")


def gen_profiles(gpr, upstream_units, bvnr_data, upstream, commit):
    """One Rust file per shipped profile, mirroring the four C tables
    gen_profiles.py emits for it (prefix, atom, unsupported, reverse).

    The upstream validators run first, so a data file the C build refuses is
    refused here too. Opaque ids come from the profile's frozen block tag and
    do not depend on which other profiles are loaded."""
    profiles = [p for p in gpr.PROFILES if p.ns in SHIPPED_PROFILES]
    if [p.ns for p in profiles] != list(SHIPPED_PROFILES):
        raise SystemExit("upstream profile registry changed: %r"
                         % [p.ns for p in gpr.PROFILES])
    gendata = os.path.join(upstream, "src", "gendata")
    for p in profiles:
        p.doc = gpr.load(os.path.join(gendata, p.data))
        gpr.check_codes(p)
        gpr.check_codes_reachable(p)
        gpr.check_prefixes(p)
    units, pfx, allpfx, iec = gpr.native_registry()
    for p in profiles:
        gpr.check_targets_parse(p, set(units), allpfx)
        gpr.check_profile_string_bound(p)
    gpr.assign_opaque_ids(profiles)

    unit_ids = {u["name"]: u["id"] for u in upstream_units.load_units(
        os.path.join(gendata, "units.bvnr"))}
    with open(os.path.join(gendata, "prefixes.bvnr"), "rb") as f:
        iec_ids = {"iec_" + r["name"]: r["id"]
                   for r in bvnr_data.load(f.read())["iec_prefixes"]}

    files, summary = {}, []
    for p in profiles:
        out = [header(commit, p.data)]
        out.append("use super::super::profiles::{Atom, AtomTarget, ProfilePrefix, "
                   "Reverse};\n\n")
        prefixes = sorted(p.list("prefixes"),
                          key=lambda r: (-len(utf8(r["code"])), utf8(r["code"])))
        out.append("/// Prefix spellings, longest first, then by bytes: the order "
                   "the C parser tries them in.\n")
        out.append("pub(crate) static PREFIXES: [ProfilePrefix; %d] = [\n"
                   % len(prefixes))
        for r in prefixes:
            out.append("    ProfilePrefix { code: %s, decade: %d },\n"
                       % (rust_str(r["code"]), int(r["decade"])))
        out.append("];\n\n")

        atoms = []
        for m in p.list("mapped"):
            atoms.append((m["code"], "AtomTarget::Native(%s)" % rust_str(m["bovnar"]),
                          bool(m.get("metric", False))))
        for a in p.list("opaque"):
            atoms.append((a["code"], "AtomTarget::Opaque(%d)" % a["id"],
                          bool(a.get("metric", False))))
        atoms.sort(key=lambda r: utf8(r[0]))
        out.append("/// Every code with a translation, sorted by bytes.\n")
        out.append("pub(crate) static ATOMS: [Atom; %d] = [\n" % len(atoms))
        for code, target, metric in atoms:
            out.append("    Atom { code: %s, target: %s, metric: %s },\n"
                       % (rust_str(code), target, "true" if metric else "false"))
        out.append("];\n\n")

        unsup = sorted(p.list("unsupported"), key=lambda r: utf8(r["code"]))
        out.append("/// Codes of the vocabulary that have no Bovnar representation "
                   "(`error_unit_profile_unsupported`), sorted by bytes.\n")
        out.append("pub(crate) static UNSUPPORTED: [&str; %d] = [\n" % len(unsup))
        for r in unsup:
            out.append("    // %s\n    %s,\n" % (r["why"].replace("\n", " "),
                                                rust_str(r["code"])))
        out.append("];\n\n")

        rev = reverse_rows(p, units, pfx, iec, gpr.decompose_target)
        out.append("/// Which code writes a native base unit back, and the decade "
                   "that code already carries (the C reverse table, same order).\n")
        out.append("pub(crate) static REVERSE: [Reverse; %d] = [\n" % len(rev))
        for name, code, decade, metric, iecp in rev:
            out.append("    Reverse { base: %d, code: %s, decade: %d, metric: %s, "
                       "iec: %d }, // %s\n"
                       % (unit_ids[name], rust_str(code), decade,
                          "true" if metric else "false",
                          iec_ids[iecp] if iecp else 0, name))
        out.append("];\n\n")

        opaque = p.list("opaque")
        out.append("/// Id of this profile's first opaque unit; row `i` of "
                   "[`OPAQUE`] has id `OPAQUE_FIRST + i`.\n")
        out.append("pub(crate) const OPAQUE_FIRST: u32 = %d;\n\n" % p.opaque_first)
        out.append("/// The opaque units as (C enumerator suffix, code), in id "
                   "order.\n")
        out.append("pub(crate) static OPAQUE: [(&str, &str); %d] = [\n" % len(opaque))
        for a in opaque:
            out.append("    (%s, %s),\n" % (rust_str(a["name"]), rust_str(a["code"])))
        out.append("];\n")
        files["profile_%s.rs" % p.cname] = "".join(out)
        summary.append("%s %d/%d/%d/%d" % (p.ns, len(atoms), len(unsup),
                                           len(prefixes), len(rev)))
    return files, summary


def reverse_rows(p, units, pfx, iec, decompose_target):
    """The rows of gen_profiles.py's gen_reverse_table, as data.

    Same selection: a flat profile keeps the first eligible row per
    (base, decade, binary prefix) in declaration order, an expression profile
    the shortest code per base, ties alphabetical. `.reverse = false` removes
    a row from the running."""
    if not p.writable:
        return []
    flat = p.grammar == "flat"
    best, seen = {}, set()
    for order_index, m in enumerate(p.list("mapped")):
        d = decompose_target(m["bovnar"], units, pfx, iec if flat else None)
        if d is None:
            continue
        name, decade, iecp = d
        code = m["code"]
        slot = (name, decade, iecp) if flat else name
        seen.add(slot)
        if not m.get("reverse", True):
            continue
        key = (order_index,) if flat else (len(utf8(code)), code)
        if slot not in best or key < best[slot][0]:
            best[slot] = (key, code, decade, bool(m.get("metric", False)), iecp)
    if seen - set(best):
        raise SystemExit("%s: a unit this profile can read and cannot write" % p.ns)
    order = sorted(best, key=lambda k: (k[0], k[1], k[2] or "")
                   if flat else (k, 0, ""))
    rows = []
    for slot in order:
        _key, code, decade, metric, iecp = best[slot]
        rows.append((slot[0] if flat else slot, code, decade, metric, iecp))
    return rows


def main():
    args = [a for a in sys.argv[1:] if a != "--check"]
    check = "--check" in sys.argv[1:]
    if len(args) != 1:
        raise SystemExit(__doc__)
    upstream = os.path.abspath(args[0])
    # The upstream generators read their data relative to their own location
    # and are imported from there; they only define functions at import time.
    sys.dont_write_bytecode = True  # leave the read-only upstream tree untouched
    sys.path.insert(0, upstream)
    import bvnr_data
    import gen_currencies as upstream_currencies
    import gen_profiles as upstream_profiles
    import gen_prefixes as upstream_prefixes
    import gen_units as upstream_units

    commit = upstream_commit(upstream)
    units_rs, n_units, n_aliases = gen_units(upstream_units, bvnr_data, upstream, commit)
    prefixes_rs, n_prefixes = gen_prefixes(upstream_prefixes, bvnr_data, upstream, commit)
    currencies_rs, n_curr = gen_currencies(upstream_currencies, bvnr_data, upstream, commit)
    files = {
        "units.rs": units_rs,
        "prefixes.rs": prefixes_rs,
        "currencies.rs": currencies_rs,
    }
    profile_files, profile_summary = gen_profiles(
        upstream_profiles, upstream_units, bvnr_data, upstream, commit)
    files.update(profile_files)

    stale = []
    for name, text in files.items():
        dest = os.path.normpath(os.path.join(OUT_DIR, name))
        try:
            with open(dest, encoding="utf-8") as f:
                current = f.read()
        except FileNotFoundError:
            current = None
        if current == text:
            continue
        if check:
            stale.append(dest)
            continue
        os.makedirs(os.path.dirname(dest), exist_ok=True)
        with open(dest, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    if stale:
        raise SystemExit("generated tables are stale; rerun scripts/gen-tables.py:\n  "
                         + "\n  ".join(stale))
    print("%d units (%d spellings), %d prefixes, %d currencies"
          % (n_units, n_aliases, n_prefixes, n_curr))
    print("profiles (atoms/unsupported/prefixes/reverse): "
          + ", ".join(profile_summary))


if __name__ == "__main__":
    main()
